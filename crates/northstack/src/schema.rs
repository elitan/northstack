//! Generates Rust types from the Postgres schema (`northstack gen-db`).
//!
//! For every table it writes a row struct, and for every enum a Rust enum. All
//! of them derive `sqlx::FromRow`/`sqlx::Type`, `serde` and `ts_rs::TS`, so the
//! same type is used in queries (`query_as!(Note, ...)`) and flows on to the
//! TypeScript client. Postgres is the source of truth:
//!
//! ```text
//! migration -> Postgres -> app/src/db/schema.rs -> web/src/rpc/types/*.ts
//! ```
//!
//! Conventions, controlled with SQL comments:
//!
//! - `COMMENT ON TABLE t IS '...'` and `COMMENT ON COLUMN ...` become doc
//!   comments in Rust and TypeScript.
//! - A column comment containing `@private` keeps the column in Rust but out of
//!   JSON and TypeScript (password hashes, internal flags, ...).
//! - A table comment containing `@name(Person)` overrides the struct name.
//!   By default the name is the singular PascalCase of the table: `notes` ->
//!   `Note`, `categories` -> `Category`.
//! - Tables starting with `_` or `northstack_` are skipped. So are tables with
//!   `@skip` in their comment.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use sqlx::PgPool;

const HEADER: &str =
    "//! Generated by `northstack gen-db` from the Postgres schema. Do not edit by hand.
//! Change the schema with a migration, then run `just check`.
";

#[derive(Debug, sqlx::FromRow)]
struct ColumnRow {
    table_name: String,
    table_comment: Option<String>,
    column_name: String,
    not_null: bool,
    type_name: String,
    type_kind: String,
    elem_name: Option<String>,
    elem_kind: Option<String>,
    column_comment: Option<String>,
}

#[derive(Debug, sqlx::FromRow)]
struct EnumRow {
    type_name: String,
    label: String,
}

/// A Postgres schema, read from the catalog.
#[derive(Debug, Default)]
pub struct Schema {
    tables: BTreeMap<String, Table>,
    enums: BTreeMap<String, Vec<String>>,
}

#[derive(Debug)]
struct Table {
    comment: Option<String>,
    columns: Vec<Column>,
}

#[derive(Debug)]
struct Column {
    name: String,
    not_null: bool,
    ty: PgType,
    comment: Option<String>,
}

#[derive(Debug, Clone)]
enum PgType {
    Base(String),
    Enum(String),
    Array(Box<PgType>),
    Unsupported(String),
}

impl Schema {
    /// Read tables and enums from `schema` (usually `public`).
    pub async fn load(pool: &PgPool, schema: &str) -> sqlx::Result<Self> {
        let columns: Vec<ColumnRow> = sqlx::query_as(
            r#"
            SELECT
                c.relname::text                         AS table_name,
                obj_description(c.oid, 'pg_class')      AS table_comment,
                a.attname::text                         AS column_name,
                a.attnotnull                            AS not_null,
                t.typname::text                         AS type_name,
                t.typtype::text                         AS type_kind,
                et.typname::text                        AS elem_name,
                et.typtype::text                        AS elem_kind,
                col_description(c.oid, a.attnum)        AS column_comment
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
            JOIN pg_type t ON t.oid = a.atttypid
            LEFT JOIN pg_type et ON et.oid = t.typelem AND t.typcategory = 'A'
            WHERE n.nspname = $1 AND c.relkind IN ('r', 'p')
            ORDER BY c.relname, a.attnum
            "#,
        )
        .bind(schema)
        .fetch_all(pool)
        .await?;

        let enum_rows: Vec<EnumRow> = sqlx::query_as(
            r#"
            SELECT t.typname::text AS type_name, e.enumlabel::text AS label
            FROM pg_type t
            JOIN pg_enum e ON e.enumtypid = t.oid
            JOIN pg_namespace n ON n.oid = t.typnamespace
            WHERE n.nspname = $1
            ORDER BY t.typname, e.enumsortorder
            "#,
        )
        .bind(schema)
        .fetch_all(pool)
        .await?;

        let mut out = Schema::default();
        for e in enum_rows {
            out.enums.entry(e.type_name).or_default().push(e.label);
        }
        for c in columns {
            if c.table_name.starts_with('_')
                || c.table_name.starts_with("northstack_")
                || has_tag(c.table_comment.as_deref(), "@skip")
            {
                continue;
            }
            let ty = map_type(
                &c.type_name,
                &c.type_kind,
                c.elem_name.as_deref(),
                c.elem_kind.as_deref(),
            );
            let table = out.tables.entry(c.table_name).or_insert_with(|| Table {
                comment: c.table_comment.clone(),
                columns: Vec::new(),
            });
            table.columns.push(Column {
                name: c.column_name,
                not_null: c.not_null,
                ty,
                comment: c.column_comment,
            });
        }
        Ok(out)
    }

    /// Render `schema.rs`. Fails with a list of every column whose type has
    /// no mapping, so all problems are reported at once.
    pub fn render(&self) -> anyhow::Result<String> {
        let mut problems = Vec::new();
        let mut names: BTreeMap<String, String> = BTreeMap::new();
        let mut claim = |rust: String, owner: String, problems: &mut Vec<String>| {
            if let Some(prev) = names.insert(rust.clone(), owner.clone()) {
                problems.push(format!(
                    "{owner} and {prev} would both be named `{rust}`; add `@name(Other)` to one table comment"
                ));
            }
        };

        let mut out = String::from(HEADER);
        out.push_str("\nuse serde::{Deserialize, Serialize};\nuse ts_rs::TS;\n");

        for (pg_name, labels) in &self.enums {
            let name = pascal(pg_name);
            claim(name.clone(), format!("enum {pg_name}"), &mut problems);
            writeln!(out, "\n/// Postgres enum `{pg_name}`.")?;
            out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n");
            out.push_str("#[derive(Serialize, Deserialize, sqlx::Type, TS)]\n");
            writeln!(out, "#[sqlx(type_name = \"{pg_name}\")]")?;
            writeln!(out, "pub enum {name} {{")?;
            let mut seen = BTreeSet::new();
            for (i, label) in labels.iter().enumerate() {
                let variant = pascal(label);
                if variant.is_empty() || !seen.insert(variant.clone()) {
                    problems.push(format!(
                        "enum {pg_name}: label {label:?} can't become a Rust variant"
                    ));
                    continue;
                }
                if i == 0 {
                    out.push_str("    #[default]\n");
                }
                writeln!(out, "    #[serde(rename = {label:?})]")?;
                writeln!(out, "    #[sqlx(rename = {label:?})]")?;
                writeln!(out, "    {variant},")?;
            }
            out.push_str("}\n");
        }

        for (table_name, table) in &self.tables {
            let name = tag_value(table.comment.as_deref(), "@name")
                .unwrap_or_else(|| pascal(&singular(table_name)));
            claim(name.clone(), format!("table {table_name}"), &mut problems);
            out.push('\n');
            write_doc(
                &mut out,
                "",
                table.comment.as_deref(),
                &format!("Row of table `{table_name}`."),
            )?;
            out.push_str(
                "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, sqlx::FromRow, TS)]\n",
            );
            out.push_str("#[serde(rename_all = \"camelCase\")]\n");
            writeln!(out, "pub struct {name} {{")?;
            for col in &table.columns {
                let base = match self.rust_type(&col.ty) {
                    Ok(t) => t,
                    Err(pg) => {
                        problems.push(format!(
                            "{table_name}.{}: Postgres type `{pg}` is not supported; use a supported type or add a mapping in northstack/src/schema.rs",
                            col.name
                        ));
                        continue;
                    }
                };
                let ty = if col.not_null {
                    base
                } else {
                    format!("Option<{base}>")
                };
                write_doc(&mut out, "    ", col.comment.as_deref(), "")?;
                if has_tag(col.comment.as_deref(), "@private") {
                    out.push_str("    #[serde(skip_serializing, default)]\n    #[ts(skip)]\n");
                }
                writeln!(out, "    pub {}: {ty},", field_name(&col.name))?;
            }
            out.push_str("}\n");
        }

        if !problems.is_empty() {
            anyhow::bail!(
                "cannot generate schema types:\n  - {}",
                problems.join("\n  - ")
            );
        }
        Ok(out)
    }

    fn rust_type(&self, ty: &PgType) -> Result<String, String> {
        match ty {
            PgType::Base(t) => Ok(t.clone()),
            PgType::Enum(e) if self.enums.contains_key(e) => Ok(pascal(e)),
            PgType::Enum(e) => Err(e.clone()),
            PgType::Array(inner) => Ok(format!("Vec<{}>", self.rust_type(inner)?)),
            PgType::Unsupported(t) => Err(t.clone()),
        }
    }
}

fn map_type(name: &str, kind: &str, elem: Option<&str>, elem_kind: Option<&str>) -> PgType {
    if let (Some(elem), Some(elem_kind)) = (elem, elem_kind) {
        return PgType::Array(Box::new(map_type(elem, elem_kind, None, None)));
    }
    if kind == "e" {
        return PgType::Enum(name.to_string());
    }
    let rust = match name {
        "bool" => "bool",
        "int2" => "i16",
        "int4" => "i32",
        "int8" => "i64",
        "float4" => "f32",
        "float8" => "f64",
        "numeric" => "sqlx::types::BigDecimal",
        "text" | "varchar" | "bpchar" | "citext" | "name" => "String",
        "uuid" => "uuid::Uuid",
        "timestamptz" => "chrono::DateTime<chrono::Utc>",
        "timestamp" => "chrono::NaiveDateTime",
        "date" => "chrono::NaiveDate",
        "time" => "chrono::NaiveTime",
        "json" | "jsonb" => "serde_json::Value",
        "bytea" => "Vec<u8>",
        other => return PgType::Unsupported(other.to_string()),
    };
    PgType::Base(rust.to_string())
}

fn write_doc(
    out: &mut String,
    indent: &str,
    comment: Option<&str>,
    fallback: &str,
) -> std::fmt::Result {
    let text = comment.map(strip_tags).filter(|c| !c.is_empty());
    match text {
        Some(text) => {
            for line in text.lines() {
                let line = line.trim_end();
                if line.is_empty() {
                    writeln!(out, "{indent}///")?;
                } else {
                    writeln!(out, "{indent}/// {line}")?;
                }
            }
        }
        None if !fallback.is_empty() => writeln!(out, "{indent}/// {fallback}")?,
        None => {}
    }
    Ok(())
}

fn has_tag(comment: Option<&str>, tag: &str) -> bool {
    comment.is_some_and(|c| {
        c.split_whitespace()
            .any(|w| w == tag || w.starts_with(&format!("{tag}(")))
    })
}

/// `@name(Person)` -> `Some("Person")`.
fn tag_value(comment: Option<&str>, tag: &str) -> Option<String> {
    let c = comment?;
    let start = c.find(&format!("{tag}("))? + tag.len() + 1;
    let end = c[start..].find(')')? + start;
    Some(c[start..end].trim().to_string()).filter(|s| !s.is_empty())
}

/// Remove `@tags` from a comment, keeping the prose.
fn strip_tags(comment: &str) -> String {
    comment
        .lines()
        .map(|line| {
            line.split_whitespace()
                .filter(|w| !w.starts_with('@'))
                .collect::<Vec<_>>()
                .join(" ")
        })
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string()
}

/// `note_priority` -> `NotePriority`, `in-progress` -> `InProgress`.
fn pascal(s: &str) -> String {
    let mut out = String::new();
    for part in s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
    {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    out
}

/// Naive English singular for table names. Override with `@name(...)`.
fn singular(s: &str) -> String {
    let (head, last) = match s.rfind('_') {
        Some(i) => (&s[..=i], &s[i + 1..]),
        None => ("", s),
    };
    let word = if let Some(stem) = last.strip_suffix("ies") {
        format!("{stem}y")
    } else if last.ends_with("sses")
        || last.ends_with("xes")
        || last.ends_with("ches")
        || last.ends_with("shes")
    {
        last[..last.len() - 2].to_string()
    } else if last.ends_with("ss") || last.ends_with("us") || last.ends_with("is") {
        last.to_string()
    } else if let Some(stem) = last.strip_suffix('s') {
        stem.to_string()
    } else {
        last.to_string()
    };
    format!("{head}{word}")
}

fn field_name(column: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe",
        "use", "where", "while", "yield", "box", "macro", "priv", "typeof", "virtual", "final",
        "override", "abstract", "become", "do", "try", "gen",
    ];
    if KEYWORDS.contains(&column) {
        format!("r#{column}")
    } else {
        column.to_string()
    }
}

/// Format Rust source with rustfmt if available, so the generated file is
/// stable under `cargo fmt`.
pub fn rustfmt(source: &str) -> String {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn();
    let Ok(mut child) = child else {
        return source.to_string();
    };
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(source.as_bytes());
    }
    match child.wait_with_output() {
        Ok(out) if out.status.success() && !out.stdout.is_empty() => {
            String::from_utf8(out.stdout).unwrap_or_else(|_| source.to_string())
        }
        _ => source.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn naming() {
        assert_eq!(singular("notes"), "note");
        assert_eq!(singular("categories"), "category");
        assert_eq!(singular("addresses"), "address");
        assert_eq!(singular("boxes"), "box");
        assert_eq!(singular("user_settings"), "user_setting");
        assert_eq!(singular("person"), "person");
        assert_eq!(pascal("note_digest"), "NoteDigest");
        assert_eq!(pascal("in-progress"), "InProgress");
        assert_eq!(pascal("2fa"), "V2fa");
        assert_eq!(field_name("type"), "r#type");
    }

    #[test]
    fn tags() {
        assert!(has_tag(Some("Password hash. @private"), "@private"));
        assert!(!has_tag(Some("not private"), "@private"));
        assert_eq!(
            tag_value(Some("People. @name(Person)"), "@name").as_deref(),
            Some("Person")
        );
        assert_eq!(
            strip_tags("Hash of the password. @private"),
            "Hash of the password."
        );
    }
}
