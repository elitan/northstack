//! Generates Rust types from the SQLite schema (`northstack gen-db`).
//!
//! For every table it writes a row struct, and for every enum column a Rust
//! enum. All of them derive `sqlx::FromRow`/`sqlx::Type`, `serde` and
//! `ts_rs::TS`, so the same type is used in queries (`query_as!(Note, ...)`)
//! and flows on to the TypeScript client. The database is the source of truth:
//!
//! ```text
//! migration -> SQLite -> server/src/db/schema.rs -> web/northstack/types/*.ts
//!                     -> server/sqlx.toml (column types for the sqlx macros)
//! ```
//!
//! SQLite stores few types, so the declared column type says what a column
//! holds. `gen-db` maps it to Rust and writes `sqlx.toml`, which tells the
//! `query!`/`query_as!` macros the same, so `SELECT id ...` decodes as a `Uuid`
//! without annotations:
//!
//! | Declared type | Rust | Stored as |
//! |---|---|---|
//! | `INTEGER` | `i64` | integer |
//! | `REAL` | `f64` | float |
//! | `TEXT` | `String` | text |
//! | `TEXT CHECK (col IN ('a', 'b'))` | generated enum | text |
//! | `BOOLEAN` | `bool` | 0 / 1 |
//! | `UUID` | `uuid::Uuid` | 16-byte blob |
//! | `TIMESTAMP` | `chrono::DateTime<Utc>` | text, `2026-11-15T10:00:00.123+00:00` |
//! | `DATE` | `chrono::NaiveDate` | text, `2026-11-15` |
//! | `JSON` | `serde_json::Value` | text |
//! | `BLOB` | `Vec<u8>` | blob |
//!
//! Conventions, written as SQL comments inside `CREATE TABLE`:
//!
//! - A comment on the `CREATE TABLE name (` line documents the table. A
//!   comment above a column, or after it on the same line, documents the
//!   column. Both become doc comments in Rust and TypeScript.
//! - `@private` on a column keeps it in Rust but out of JSON and TypeScript
//!   (password hashes, internal flags, ...).
//! - `@name(Person)` on the table overrides the struct name. By default it is
//!   the singular PascalCase of the table: `notes` -> `Note`.
//! - `@enum(Status)` on an enum column overrides the enum name. By default it
//!   is struct + column: `notes.priority` -> `NotePriority`.
//! - Tables starting with `_`, `sqlite_` or `northstack_` are skipped. So are
//!   tables with `@skip` in their comment, and virtual tables (FTS5, ...)
//!   with their shadow tables.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use sqlx::SqlitePool;

const HEADER: &str =
    "//! Generated by `northstack gen-db` from the SQLite schema. Do not edit by hand.
//! Change the schema with a migration, then run `just check`.
";

/// The default every `TIMESTAMP` column must use, so stored times compare
/// correctly with each other and with times bound from Rust.
pub const TIMESTAMP_DEFAULT: &str = crate::db::NOW;

#[derive(Debug, sqlx::FromRow)]
struct TableRow {
    name: String,
    sql: String,
}

#[derive(Debug, sqlx::FromRow)]
struct ColumnRow {
    name: String,
    #[sqlx(rename = "type")]
    ty: String,
    notnull: bool,
    pk: i64,
    dflt_value: Option<String>,
    hidden: i64,
}

/// A SQLite schema, read from `sqlite_schema` and `pragma_table_xinfo`.
#[derive(Debug, Default)]
pub struct Schema {
    tables: BTreeMap<String, Table>,
}

#[derive(Debug)]
struct Table {
    comment: Option<String>,
    columns: Vec<Column>,
}

#[derive(Debug)]
struct Column {
    name: String,
    not_null: bool,
    ty: Ty,
    comment: Option<String>,
    default: Option<String>,
}

#[derive(Debug, Clone)]
enum Ty {
    /// A Rust type, and whether sqlx's macros need an override to produce it.
    Base(&'static str, bool),
    Enum(Vec<String>),
    Unsupported(String),
}

impl Schema {
    /// Read every table of the main database.
    pub async fn load(pool: &SqlitePool) -> sqlx::Result<Self> {
        // Ordinary tables only: virtual tables (FTS5, ...) and their shadow
        // tables have untyped columns and are not row types.
        let tables: Vec<TableRow> = sqlx::query_as(
            "SELECT s.name, s.sql FROM sqlite_schema s
             JOIN pragma_table_list l ON l.schema = 'main' AND l.name = s.name AND l.type = 'table'
             WHERE s.type = 'table' AND s.sql IS NOT NULL ORDER BY s.name",
        )
        .fetch_all(pool)
        .await?;

        let mut out = Schema::default();
        for t in tables {
            let parsed = parse_create_table(&t.sql);
            if t.name.starts_with('_')
                || t.name.starts_with("sqlite_")
                || t.name.starts_with("northstack_")
                || has_tag(parsed.comment.as_deref(), "@skip")
            {
                continue;
            }
            let rows: Vec<ColumnRow> = sqlx::query_as(
                r#"SELECT name, type, "notnull", pk, dflt_value, hidden FROM pragma_table_xinfo($1) ORDER BY cid"#,
            )
            .bind(&t.name)
            .fetch_all(pool)
            .await?;
            let mut columns = Vec::new();
            for c in rows {
                // 1 = hidden column of a virtual table; 2/3 = generated columns (kept).
                if c.hidden == 1 {
                    continue;
                }
                let info = parsed.columns.get(&c.name.to_ascii_lowercase());
                let ty = match info.and_then(|i| i.enum_values.clone()) {
                    Some(values) => Ty::Enum(values),
                    None => map_type(&c.ty),
                };
                let integer_pk = c.pk > 0 && c.ty.eq_ignore_ascii_case("INTEGER");
                columns.push(Column {
                    not_null: c.notnull || integer_pk,
                    comment: info.and_then(|i| i.comment.clone()),
                    default: c.dflt_value,
                    name: c.name,
                    ty,
                });
            }
            out.tables.insert(
                t.name,
                Table {
                    comment: parsed.comment,
                    columns,
                },
            );
        }
        Ok(out)
    }

    /// Render `schema.rs`. Fails with a list of every problem (unsupported
    /// types, name collisions, ...), so all of them are reported at once.
    pub fn render(&self) -> anyhow::Result<String> {
        let mut problems = Vec::new();
        let mut names: BTreeMap<String, String> = BTreeMap::new();
        let mut claim = |rust: String, owner: String, problems: &mut Vec<String>| {
            if let Some(prev) = names.insert(rust.clone(), owner.clone()) {
                problems.push(format!(
                    "{owner} and {prev} would both be named `{rust}`; rename one with a `@name(Other)` (table) or `@enum(Other)` (column) comment"
                ));
            }
        };

        let mut enums = String::new();
        let mut structs = String::new();
        for (table_name, table) in &self.tables {
            if !is_plain_identifier(table_name) {
                problems.push(format!(
                    "table {table_name:?}: use a lowercase snake_case name"
                ));
                continue;
            }
            let name = self.struct_name(table_name, table);
            claim(name.clone(), format!("table {table_name}"), &mut problems);
            structs.push('\n');
            write_doc(
                &mut structs,
                "",
                table.comment.as_deref(),
                &format!("Row of table `{table_name}`."),
            )?;
            structs.push_str(
                "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, sqlx::FromRow, TS)]\n",
            );
            structs.push_str("#[serde(rename_all = \"camelCase\")]\n");
            writeln!(structs, "pub struct {name} {{")?;
            for col in &table.columns {
                let where_ = format!("{table_name}.{}", col.name);
                if !is_plain_identifier(&col.name) {
                    problems.push(format!("{where_}: use a lowercase snake_case name"));
                    continue;
                }
                let base = match &col.ty {
                    Ty::Base(rust, _) => rust.to_string(),
                    Ty::Enum(values) => {
                        let enum_name = enum_name(&name, col);
                        claim(enum_name.clone(), format!("column {where_}"), &mut problems);
                        write_enum(
                            &mut enums,
                            &enum_name,
                            &where_,
                            values,
                            col.default.as_deref(),
                            &mut problems,
                        )?;
                        enum_name
                    }
                    Ty::Unsupported(t) => {
                        problems.push(unsupported(&where_, t));
                        continue;
                    }
                };
                if matches!(col.ty, Ty::Base("chrono::DateTime<chrono::Utc>", _))
                    && let Some(d) = col.default.as_deref()
                    && unparen(d) != TIMESTAMP_DEFAULT
                {
                    problems.push(format!(
                        "{where_}: a TIMESTAMP default must be ({TIMESTAMP_DEFAULT}), not {d}; other formats (like CURRENT_TIMESTAMP) don't sort correctly against times from Rust"
                    ));
                }
                let ty = if col.not_null {
                    base
                } else {
                    format!("Option<{base}>")
                };
                write_doc(&mut structs, "    ", col.comment.as_deref(), "")?;
                if has_tag(col.comment.as_deref(), "@private") {
                    structs.push_str("    #[serde(skip_serializing, default)]\n    #[ts(skip)]\n");
                }
                writeln!(structs, "    pub {}: {ty},", field_name(&col.name))?;
            }
            structs.push_str("}\n");
        }

        if !problems.is_empty() {
            anyhow::bail!(
                "cannot generate schema types:\n  - {}",
                problems.join("\n  - ")
            );
        }
        let mut out = String::from(HEADER);
        // No imports for an empty schema: they'd be unused (a warning, and
        // `just verify` treats warnings as errors).
        if !self.tables.is_empty() {
            out.push_str("\nuse serde::{Deserialize, Serialize};\nuse ts_rs::TS;\n");
        }
        out.push_str(&enums);
        out.push_str(&structs);
        Ok(out)
    }

    /// Render `sqlx.toml`: the Rust type of every column the sqlx macros
    /// can't infer from SQLite alone (UUIDs, timestamps, JSON, enums).
    /// `module` is the Rust path of the generated types, e.g. `crate::db`.
    pub fn render_sqlx_toml(&self, module: &str) -> String {
        let mut out = String::from(
            "# Generated by `northstack gen-db` from the SQLite schema. Do not edit by hand.\n\
             # Tells the sqlx query macros the Rust type of columns SQLite can't describe.\n",
        );
        for (table_name, table) in &self.tables {
            let name = self.struct_name(table_name, table);
            let overrides: Vec<(String, String)> = table
                .columns
                .iter()
                .filter_map(|col| match &col.ty {
                    Ty::Base(rust, true) => Some((col.name.clone(), rust.to_string())),
                    Ty::Enum(_) => Some((
                        col.name.clone(),
                        format!("{module}::{}", enum_name(&name, col)),
                    )),
                    _ => None,
                })
                .collect();
            if overrides.is_empty() {
                continue;
            }
            let _ = writeln!(out, "\n[macros.table-overrides.'{table_name}']");
            for (col, rust) in overrides {
                let _ = writeln!(out, "'{col}' = \"{rust}\"");
            }
        }
        out
    }

    fn struct_name(&self, table_name: &str, table: &Table) -> String {
        tag_value(table.comment.as_deref(), "@name")
            .unwrap_or_else(|| pascal(&singular(table_name)))
    }
}

fn enum_name(struct_name: &str, col: &Column) -> String {
    tag_value(col.comment.as_deref(), "@enum")
        .unwrap_or_else(|| format!("{struct_name}{}", pascal(&col.name)))
}

fn write_enum(
    out: &mut String,
    name: &str,
    column: &str,
    values: &[String],
    default: Option<&str>,
    problems: &mut Vec<String>,
) -> std::fmt::Result {
    // The Rust default is the column's SQL default, else the first value.
    let default = default
        .map(unparen)
        .and_then(|d| d.strip_prefix('\'')?.strip_suffix('\'').map(str::to_string))
        .filter(|d| values.contains(d))
        .unwrap_or_else(|| values[0].clone());
    writeln!(out, "\n/// Values of `{column}`.")?;
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n");
    out.push_str("#[derive(Serialize, Deserialize, sqlx::Type, TS)]\n");
    writeln!(out, "pub enum {name} {{")?;
    let mut seen = BTreeSet::new();
    for value in values {
        let variant = pascal(value);
        if variant.is_empty() || !seen.insert(variant.clone()) {
            problems.push(format!(
                "{column}: value {value:?} can't become a Rust enum variant"
            ));
            continue;
        }
        if *value == default {
            out.push_str("    #[default]\n");
        }
        writeln!(out, "    #[serde(rename = {value:?})]")?;
        writeln!(out, "    #[sqlx(rename = {value:?})]")?;
        writeln!(out, "    {variant},")?;
    }
    out.push_str("}\n");
    Ok(())
}

fn unsupported(column: &str, declared: &str) -> String {
    let upper = declared.to_ascii_uppercase();
    let hint = if declared.trim().is_empty() {
        "give the column a type (INTEGER, REAL, TEXT, BOOLEAN, UUID, TIMESTAMP, DATE, JSON or BLOB)"
            .to_string()
    } else if upper.contains("NUM") || upper.contains("DEC") || upper.contains("MONEY") {
        "SQLite has no exact decimals; store money as INTEGER cents, or use REAL".to_string()
    } else {
        "use INTEGER, REAL, TEXT, BOOLEAN, UUID, TIMESTAMP, DATE, JSON or BLOB".to_string()
    };
    format!("{column}: type `{declared}` is not supported; {hint}")
}

/// Map a declared column type to Rust. The bool says whether the sqlx macros
/// need an override in sqlx.toml to produce that type.
fn map_type(declared: &str) -> Ty {
    let upper = declared.trim().to_ascii_uppercase();
    // Strip a size like VARCHAR(20).
    let base = upper.split('(').next().unwrap_or("").trim();
    match base {
        "BOOLEAN" | "BOOL" => Ty::Base("bool", false),
        "UUID" => Ty::Base("uuid::Uuid", true),
        "TIMESTAMP" | "DATETIME" => Ty::Base("chrono::DateTime<chrono::Utc>", true),
        "DATE" => Ty::Base("chrono::NaiveDate", false),
        "JSON" => Ty::Base("serde_json::Value", true),
        "INTEGER" | "INT" | "BIGINT" => Ty::Base("i64", false),
        "REAL" | "DOUBLE" | "FLOAT" => Ty::Base("f64", false),
        "TEXT" | "VARCHAR" | "CHAR" => Ty::Base("String", false),
        "BLOB" => Ty::Base("Vec<u8>", false),
        _ => Ty::Unsupported(declared.to_string()),
    }
}

/// `(x)` -> `x` (SQLite reports `DEFAULT (expr)` with or without parens).
fn unparen(s: &str) -> &str {
    let s = s.trim();
    match s.strip_prefix('(').and_then(|s| s.strip_suffix(')')) {
        Some(inner) if balanced(inner) => inner.trim(),
        _ => s,
    }
}

fn balanced(s: &str) -> bool {
    let mut depth = 0i32;
    for c in s.chars() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth < 0 {
                    return false;
                }
            }
            _ => {}
        }
    }
    depth == 0
}

fn is_plain_identifier(s: &str) -> bool {
    !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !s.starts_with(|c: char| c.is_ascii_digit())
}

// --- CREATE TABLE parsing ----------------------------------------------------
//
// SQLite keeps the original CREATE TABLE text, comments included (and appends
// columns added with ALTER TABLE). We read comments and `CHECK (col IN (...))`
// enums from it; everything else comes from `pragma_table_xinfo`.

#[derive(Debug, Default)]
struct ParsedTable {
    comment: Option<String>,
    /// Keyed by lowercase column name.
    columns: BTreeMap<String, ParsedColumn>,
}

#[derive(Debug, Default, Clone)]
struct ParsedColumn {
    comment: Option<String>,
    enum_values: Option<Vec<String>>,
}

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    /// Identifier, keyword or number; quoted identifiers are unquoted.
    Word(String),
    Str(String),
    Punct(char),
    Comment(String),
    Newline,
}

fn tokenize(sql: &str) -> Vec<Tok> {
    let chars: Vec<char> = sql.chars().collect();
    let mut toks = Vec::new();
    let mut i = 0;
    let read_until = |i: &mut usize, end: char| -> String {
        let mut s = String::new();
        while *i < chars.len() {
            if chars[*i] == end {
                // Doubled quote = escaped quote.
                if *i + 1 < chars.len() && chars[*i + 1] == end && end != ']' {
                    s.push(end);
                    *i += 2;
                    continue;
                }
                *i += 1;
                break;
            }
            s.push(chars[*i]);
            *i += 1;
        }
        s
    };
    while i < chars.len() {
        let c = chars[i];
        if c == '\n' {
            toks.push(Tok::Newline);
            i += 1;
        } else if c.is_whitespace() {
            i += 1;
        } else if c == '-' && chars.get(i + 1) == Some(&'-') {
            let start = i + 2;
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
            toks.push(Tok::Comment(
                chars[start..i]
                    .iter()
                    .collect::<String>()
                    .trim()
                    .to_string(),
            ));
        } else if c == '/' && chars.get(i + 1) == Some(&'*') {
            let start = i + 2;
            i += 2;
            while i + 1 < chars.len() && !(chars[i] == '*' && chars[i + 1] == '/') {
                i += 1;
            }
            let text: String = chars[start..i.min(chars.len())].iter().collect();
            i = (i + 2).min(chars.len());
            toks.push(Tok::Comment(text.trim().to_string()));
        } else if c == '\'' {
            i += 1;
            toks.push(Tok::Str(read_until(&mut i, '\'')));
        } else if c == '"' || c == '`' || c == '[' {
            i += 1;
            let end = match c {
                '[' => ']',
                other => other,
            };
            toks.push(Tok::Word(read_until(&mut i, end)));
        } else if c.is_alphanumeric() || c == '_' || c == '$' {
            let start = i;
            while i < chars.len()
                && (chars[i].is_alphanumeric() || chars[i] == '_' || chars[i] == '$')
            {
                i += 1;
            }
            toks.push(Tok::Word(chars[start..i].iter().collect()));
        } else {
            toks.push(Tok::Punct(c));
            i += 1;
        }
    }
    toks
}

/// One top-level item of `CREATE TABLE t ( item, item, ... )`.
#[derive(Default)]
struct Item {
    toks: Vec<Tok>,
    comments: Vec<String>,
}

fn parse_create_table(sql: &str) -> ParsedTable {
    let toks = tokenize(sql);
    let Some(open) = toks.iter().position(|t| *t == Tok::Punct('(')) else {
        return ParsedTable::default();
    };

    let mut table_comment = Vec::new();
    let mut items: Vec<Item> = Vec::new();
    let mut current = Item::default();
    let mut pending: Vec<String> = Vec::new();
    // Still on the line where the previous item (or the opening paren) ended?
    let mut same_line = true;
    let mut depth = 1;
    for tok in &toks[open + 1..] {
        match tok {
            Tok::Newline => same_line = false,
            Tok::Comment(text) if depth == 1 => {
                if !current.toks.is_empty() {
                    // Inside an item (e.g. after its last token, before the
                    // comma or the closing paren): it documents that item.
                    current.comments.push(text.clone());
                } else if same_line {
                    match items.last_mut() {
                        Some(prev) => prev.comments.push(text.clone()),
                        None => table_comment.push(text.clone()),
                    }
                } else {
                    pending.push(text.clone());
                }
            }
            Tok::Comment(_) => {}
            Tok::Punct(',') if depth == 1 => {
                items.push(std::mem::take(&mut current));
                same_line = true;
            }
            Tok::Punct(c) => {
                if *c == '(' {
                    depth += 1;
                } else if *c == ')' {
                    depth -= 1;
                    if depth == 0 {
                        break;
                    }
                }
                start_item(&mut current, &mut pending);
                current.toks.push(tok.clone());
            }
            _ => {
                start_item(&mut current, &mut pending);
                current.toks.push(tok.clone());
            }
        }
    }
    if !current.toks.is_empty() {
        items.push(current);
    }

    let mut out = ParsedTable {
        comment: join_comments(&table_comment),
        ..Default::default()
    };
    // Column definitions first, then table constraints (which may hold
    // `CHECK (col IN (...))` for any column).
    let mut checks = Vec::new();
    for item in &items {
        let Some(Tok::Word(first)) = item.toks.first() else {
            continue;
        };
        let upper = first.to_ascii_uppercase();
        if ["CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK", "FOREIGN"].contains(&upper.as_str()) {
            checks.push(&item.toks);
            continue;
        }
        let name = first.to_ascii_lowercase();
        let col = out.columns.entry(name).or_default();
        col.comment = join_comments(&item.comments);
        checks.push(&item.toks);
    }
    for toks in checks {
        for (col, values) in find_in_checks(toks) {
            if let Some(c) = out.columns.get_mut(&col.to_ascii_lowercase()) {
                c.enum_values = Some(values);
            }
        }
    }
    out
}

fn start_item(current: &mut Item, pending: &mut Vec<String>) {
    if current.toks.is_empty() {
        current.comments.append(pending);
    }
}

fn join_comments(lines: &[String]) -> Option<String> {
    let text = lines.join("\n").trim().to_string();
    (!text.is_empty()).then_some(text)
}

/// Every `CHECK ( col IN ( 'a', 'b', ... ) )` in the tokens.
fn find_in_checks(toks: &[Tok]) -> Vec<(String, Vec<String>)> {
    let toks: Vec<&Tok> = toks.iter().filter(|t| **t != Tok::Newline).collect();
    let word = |t: &Tok, w: &str| matches!(t, Tok::Word(x) if x.eq_ignore_ascii_case(w));
    let mut out = Vec::new();
    for i in 0..toks.len() {
        if !word(toks[i], "CHECK") {
            continue;
        }
        let rest = &toks[i + 1..];
        let (Some(Tok::Punct('(')), Some(Tok::Word(col)), Some(in_), Some(Tok::Punct('('))) = (
            rest.first().copied(),
            rest.get(1).copied(),
            rest.get(2).copied(),
            rest.get(3).copied(),
        ) else {
            continue;
        };
        if !word(in_, "IN") {
            continue;
        }
        let mut values = Vec::new();
        let mut j = 4;
        let mut ok = false;
        while let Some(t) = rest.get(j) {
            match t {
                Tok::Str(s) => values.push(s.clone()),
                Tok::Punct(',') => {}
                Tok::Punct(')') => {
                    ok = rest.get(j + 1) == Some(&&Tok::Punct(')'));
                    break;
                }
                _ => break,
            }
            j += 1;
        }
        if ok && !values.is_empty() {
            out.push((col.clone(), values));
        }
    }
    out
}

fn write_doc(
    out: &mut String,
    indent: &str,
    comment: Option<&str>,
    fallback: &str,
) -> std::fmt::Result {
    let text = comment.map(strip_tags).filter(|c| !c.is_empty());
    match text {
        Some(text) => {
            for line in text.lines() {
                let line = line.trim_end();
                if line.is_empty() {
                    writeln!(out, "{indent}///")?;
                } else {
                    writeln!(out, "{indent}/// {line}")?;
                }
            }
        }
        None if !fallback.is_empty() => writeln!(out, "{indent}/// {fallback}")?,
        None => {}
    }
    Ok(())
}

fn has_tag(comment: Option<&str>, tag: &str) -> bool {
    comment.is_some_and(|c| {
        c.split_whitespace()
            .any(|w| w == tag || w.starts_with(&format!("{tag}(")))
    })
}

/// `@name(Person)` -> `Some("Person")`.
fn tag_value(comment: Option<&str>, tag: &str) -> Option<String> {
    let c = comment?;
    let start = c.find(&format!("{tag}("))? + tag.len() + 1;
    let end = c[start..].find(')')? + start;
    Some(c[start..end].trim().to_string()).filter(|s| !s.is_empty())
}

/// Remove `@tags` from a comment, keeping the prose.
fn strip_tags(comment: &str) -> String {
    comment
        .lines()
        .map(|line| {
            line.split_whitespace()
                .filter(|w| !w.starts_with('@'))
                .collect::<Vec<_>>()
                .join(" ")
        })
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string()
}

/// `note_priority` -> `NotePriority`, `in-progress` -> `InProgress`.
fn pascal(s: &str) -> String {
    let mut out = String::new();
    for part in s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
    {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    out
}

/// Naive English singular for table names. Override with `@name(...)`.
fn singular(s: &str) -> String {
    let (head, last) = match s.rfind('_') {
        Some(i) => (&s[..=i], &s[i + 1..]),
        None => ("", s),
    };
    let word = if let Some(stem) = last.strip_suffix("ies") {
        format!("{stem}y")
    } else if last.ends_with("sses")
        || last.ends_with("xes")
        || last.ends_with("ches")
        || last.ends_with("shes")
    {
        last[..last.len() - 2].to_string()
    } else if last.ends_with("ss") || last.ends_with("us") || last.ends_with("is") {
        last.to_string()
    } else if let Some(stem) = last.strip_suffix('s') {
        stem.to_string()
    } else {
        last.to_string()
    };
    format!("{head}{word}")
}

fn field_name(column: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe",
        "use", "where", "while", "yield", "box", "macro", "priv", "typeof", "virtual", "final",
        "override", "abstract", "become", "do", "try", "gen",
    ];
    if KEYWORDS.contains(&column) {
        format!("r#{column}")
    } else {
        column.to_string()
    }
}

/// Format Rust source with rustfmt if available, so the generated file is
/// stable under `cargo fmt`.
pub fn rustfmt(source: &str) -> String {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn();
    let Ok(mut child) = child else {
        return source.to_string();
    };
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(source.as_bytes());
    }
    match child.wait_with_output() {
        Ok(out) if out.status.success() && !out.stdout.is_empty() => {
            String::from_utf8(out.stdout).unwrap_or_else(|_| source.to_string())
        }
        _ => source.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn naming() {
        assert_eq!(singular("notes"), "note");
        assert_eq!(singular("categories"), "category");
        assert_eq!(singular("addresses"), "address");
        assert_eq!(singular("boxes"), "box");
        assert_eq!(singular("user_settings"), "user_setting");
        assert_eq!(singular("person"), "person");
        assert_eq!(pascal("note_digest"), "NoteDigest");
        assert_eq!(pascal("in-progress"), "InProgress");
        assert_eq!(pascal("2fa"), "V2fa");
        assert_eq!(field_name("type"), "r#type");
    }

    #[test]
    fn tags() {
        assert!(has_tag(Some("Password hash. @private"), "@private"));
        assert!(!has_tag(Some("not private"), "@private"));
        assert_eq!(
            tag_value(Some("People. @name(Person)"), "@name").as_deref(),
            Some("Person")
        );
        assert_eq!(
            strip_tags("Hash of the password. @private"),
            "Hash of the password."
        );
    }
}
