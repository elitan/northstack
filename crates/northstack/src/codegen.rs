//! Generates the TypeScript client from registered procedures.
//!
//! Output layout (all generated, never edit by hand):
//!
//! ```text
//! <dir>/types/*.ts      one file per Rust type (via ts-rs)
//! <dir>/procedures.ts   map of procedure name -> { kind, input, output }
//! <dir>/client.ts       fetch-based client: call(), RpcClientError
//! <dir>/react.ts        query()/mutation() helpers on TanStack Query
//! <dir>/api.ts          nested `api` object: api.notes.list, api.notes.create, ...
//! <dir>/index.ts        re-exports
//! ```

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS, TypeVisitor};

use crate::rpc::Rpc;

const HEADER: &str = "// Generated by northstack. Do not edit by hand; run `just check`.\n";
const CLIENT_TS: &str = include_str!("ts/client.ts");
const REACT_TS: &str = include_str!("ts/react.ts");
const INDEX_TS: &str = include_str!("ts/index.ts");

/// Type information captured for a procedure at registration time.
#[derive(Clone, Copy)]
pub(crate) struct TsInfo {
    input: fn(&Config) -> String,
    output: fn(&Config) -> String,
    export: fn(&Config, &mut Imports) -> Result<(), String>,
}

type Imports = BTreeMap<String, PathBuf>;

impl TsInfo {
    pub(crate) fn new<I: TS + 'static, O: TS + 'static>() -> Self {
        Self {
            input: |cfg| I::name(cfg),
            output: |cfg| O::name(cfg),
            export: |cfg, imports| {
                export_type::<I>(cfg, imports)?;
                export_type::<O>(cfg, imports)
            },
        }
    }
}

/// Export `T` (if it is a named type) or the named types it references
/// (for `Vec<Note>`, `Option<Note>`, ...), recording imports.
fn export_type<T: TS + 'static + ?Sized>(
    cfg: &Config,
    imports: &mut Imports,
) -> Result<(), String> {
    struct Collect<'a> {
        cfg: &'a Config,
        imports: &'a mut Imports,
        error: Option<String>,
    }
    impl TypeVisitor for Collect<'_> {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if self.error.is_some() {
                return;
            }
            match T::output_path() {
                Some(path) => {
                    self.imports.insert(T::ident(self.cfg), path);
                    if let Err(e) = T::export_all(self.cfg) {
                        self.error = Some(format!("{}: {e}", std::any::type_name::<T>()));
                    }
                }
                // Not a named type itself (e.g. Vec<T>): look inside.
                None => {
                    T::visit_dependencies(self);
                    T::visit_generics(self);
                }
            }
        }
    }
    let mut c = Collect {
        cfg,
        imports,
        error: None,
    };
    c.visit::<T>();
    match c.error {
        Some(e) => Err(e),
        None => Ok(()),
    }
}

fn ts_config(types_dir: &Path) -> Config {
    // i64 is serialized as a JSON number by serde_json.
    Config::new()
        .with_out_dir(types_dir)
        .with_large_int("number")
}

impl<S: Clone + Send + Sync + 'static> Rpc<S> {
    /// Write the TypeScript client into `dir`, replacing previous output.
    pub fn generate_ts(&self, dir: impl AsRef<Path>) -> anyhow::Result<()> {
        let dir = dir.as_ref();
        if dir.exists() {
            std::fs::remove_dir_all(dir)?;
        }
        let types_dir = dir.join("types");
        std::fs::create_dir_all(&types_dir)?;
        let cfg = ts_config(&types_dir);

        // RpcError is used by client.ts, not by procedures.ts.
        export_type::<crate::RpcError>(&cfg, &mut Imports::new()).map_err(anyhow::Error::msg)?;
        let mut imports = Imports::new();
        for (name, p) in &self.procedures {
            (p.ts.export)(&cfg, &mut imports)
                .map_err(|e| anyhow::anyhow!("exporting types for {name}: {e}"))?;
        }

        let mut out = String::from(HEADER);
        for (ident, path) in &imports {
            let module = path.with_extension("");
            writeln!(
                out,
                "import type {{ {ident} }} from \"./types/{}\";",
                module.display()
            )?;
        }
        out.push_str("\nexport type Procedures = {\n");
        for (name, p) in &self.procedures {
            writeln!(
                out,
                "  \"{name}\": {{ kind: \"{}\"; input: {}; output: {} }};",
                p.kind.as_str(),
                (p.ts.input)(&cfg),
                (p.ts.output)(&cfg),
            )?;
        }
        out.push_str("};\n");

        // Every dotted prefix of a procedure name, e.g. "notes" for "notes.list".
        let mut namespaces = std::collections::BTreeSet::new();
        for name in self.procedures.keys() {
            let parts: Vec<&str> = name.split('.').collect();
            for i in 1..parts.len() {
                namespaces.insert(parts[..i].join("."));
            }
        }
        out.push_str("\n/** Dotted prefixes of procedure names, for invalidation. */\nexport type Namespace =");
        if namespaces.is_empty() {
            out.push_str(" never");
        }
        for ns in &namespaces {
            write!(out, "\n  | \"{ns}\"")?;
        }
        out.push_str(";\n");
        std::fs::write(dir.join("procedures.ts"), out)?;
        std::fs::write(dir.join("api.ts"), self.api_ts())?;

        for (file, body) in [
            ("client.ts", CLIENT_TS),
            ("react.ts", REACT_TS),
            ("index.ts", INDEX_TS),
        ] {
            std::fs::write(dir.join(file), format!("{HEADER}{body}"))?;
        }
        Ok(())
    }

    /// `api.ts`: a nested object mirroring procedure names, so the frontend
    /// writes `api.notes.list.useSuspenseQuery(...)`.
    fn api_ts(&self) -> String {
        #[derive(Default)]
        struct Node {
            children: BTreeMap<String, Node>,
            leaf: Option<(String, crate::Kind)>,
        }
        let mut root = Node::default();
        for (name, p) in &self.procedures {
            let mut node = &mut root;
            for seg in name.split('.') {
                node = node.children.entry(seg.to_string()).or_default();
            }
            node.leaf = Some((name.to_string(), p.kind));
        }
        fn check(node: &Node, path: &str) {
            for (key, child) in &node.children {
                let full = if path.is_empty() {
                    key.clone()
                } else {
                    format!("{path}.{key}")
                };
                assert!(
                    child.leaf.is_none() || child.children.is_empty(),
                    "procedure {full:?} is also a namespace of other procedures; rename one of them"
                );
                check(child, &full);
            }
        }
        fn render(node: &Node, indent: usize, out: &mut String) {
            let pad = "  ".repeat(indent);
            for (key, child) in &node.children {
                match &child.leaf {
                    Some((name, kind)) => {
                        let f = match kind {
                            crate::Kind::Query => "query",
                            crate::Kind::Mutation => "mutation",
                        };
                        out.push_str(&format!("{pad}{key}: {f}(\"{name}\"),\n"));
                    }
                    None => {
                        out.push_str(&format!("{pad}{key}: {{\n"));
                        render(child, indent + 1, out);
                        out.push_str(&format!("{pad}}},\n"));
                    }
                }
            }
        }
        check(&root, "");
        let mut out = String::from(HEADER);
        out.push_str("import { mutation, query } from \"./react\";\n\n");
        out.push_str(
            "/** Every procedure, nested by name: `api.notes.list`, `api.notes.create`, ... */\n",
        );
        out.push_str("export const api = {\n");
        render(&root, 1, &mut out);
        out.push_str("} as const;\n");
        out
    }

    /// Returns an error describing the difference if the generated client in
    /// `dir` is out of date. Use it in a test so CI catches type drift.
    pub fn check_ts(&self, dir: impl AsRef<Path>) -> anyhow::Result<()> {
        let tmp =
            std::env::temp_dir().join(format!("northstack-ts-check-{}", uuid::Uuid::new_v4()));
        self.generate_ts(&tmp)?;
        let expected = read_tree(&tmp)?;
        let _ = std::fs::remove_dir_all(&tmp);
        let actual = read_tree(dir.as_ref()).unwrap_or_default();
        if expected != actual {
            let mut diff = Vec::new();
            for k in expected.keys().chain(actual.keys()) {
                if expected.get(k) != actual.get(k) && !diff.contains(k) {
                    diff.push(k.clone());
                }
            }
            anyhow::bail!(
                "generated TypeScript client is out of date ({}); run `just check`",
                diff.join(", ")
            );
        }
        Ok(())
    }
}

fn read_tree(dir: &Path) -> anyhow::Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    fn walk(root: &Path, dir: &Path, files: &mut BTreeMap<String, String>) -> anyhow::Result<()> {
        for entry in std::fs::read_dir(dir)? {
            let path = entry?.path();
            if path.is_dir() {
                walk(root, &path, files)?;
            } else {
                let rel = path.strip_prefix(root)?.display().to_string();
                files.insert(rel, std::fs::read_to_string(&path)?);
            }
        }
        Ok(())
    }
    walk(dir, dir, &mut files)?;
    Ok(files)
}
